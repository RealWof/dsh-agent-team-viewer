/**
 * Bundle the browser half from `src/client` fragments into `client.js`.
 *
 * The client module loader takes one browser artifact per package, so the
 * source is split into ordered fragments and concatenated inside the loader
 * factory. Edit the fragments and run `node scripts/build-client.js`; never
 * edit `client.js` by hand.
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const fragments = [
  'src/client/00-header.js',
  'src/client/07-icons.js',
  'src/client/10-settings.js',
  'src/client/locales/en.js',
  'src/client/locales/ru.js',
  'src/client/locales/zh.js',
  'src/client/locales/ja.js',
  'src/client/locales/es.js',
  'src/client/locales/fr.js',
  'src/client/locales/de.js',
  'src/client/locales/pt.js',
  'src/client/20-ui.js',
  'src/client/30-data.js',
  'src/client/40-board.js',
  'src/client/45-inspector.js',
  'src/client/47-agent.js',
  'src/client/70-registration.js',
]

const body = fragments
  .map(file => readFileSync(join(root, file), 'utf8').trimEnd())
  .join('\n\n')

const artifact = `/**
 * Agent Team viewer — generated browser bundle.
 *
 * Do not edit this file: edit src/client/** and run scripts/build-client.js.
 */
window.__ModuleLoader__.load({
  id: 'dsh-agent-team-viewer',
  factory(require) {
    const React = require('react')
    const h = React.createElement

${body}
  },
})
`

writeFileSync(join(root, 'client.js'), artifact)
console.log(`client.js: ${artifact.length} bytes from ${fragments.length} fragments`)
